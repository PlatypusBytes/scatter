import math
import subprocess
from pathlib import Path

PATH_GMSH = Path("/opt/gmsh-4.13.1-Linux64/bin/./gmsh")

def __validate_positive(name: str, value: float) -> None:
    if value <= 0:
        raise ValueError(f"{name} must be > 0, got {value}")


def _build_geo_content(x: float, y: float, z: float, elem_size: float) -> str:
    nx = max(1, math.ceil(x / elem_size))
    ny = max(1, math.ceil(y / elem_size))
    nz = max(1, math.ceil(z / elem_size))

    return f"""// Gmsh project generated by create_geo_file.py
box_x = {x};
box_y = {y};
box_z = {z};
gridsize = {elem_size};

// Create 2D rectangle mesh
Point(1) = {{0, 0, 0, gridsize}};
Point(2) = {{box_x, 0, 0, gridsize}};
Point(3) = {{box_x, box_y, 0, gridsize}};
Point(4) = {{0, box_y, 0, gridsize}};

Line(5) = {{1, 2}};
Line(6) = {{2, 3}};
Line(7) = {{3, 4}};
Line(8) = {{4, 1}};

Line Loop(9) = {{5, 6, 7, 8}};
Plane Surface(10) = 9;

// Divide lines for elements
Transfinite Line{{5, 7}} = {nx + 1};
Transfinite Line{{6, 8}} = {ny + 1};

Transfinite Surface{{10}};
Recombine Surface{{10}};

// Make 3D by extrusion
newEntities[] = Extrude {{0, 0, box_z}}{{Surface{{10}};
                                       Layers{{{nz}}};
                                       Recombine;
                                       }};

// Define volume
Physical Volume("solid") = {{newEntities[1]}};
"""


def main(x: float, y: float, z: float, elem_size: float, folder: str, name:str="brick") -> tuple[Path, Path]:
    __validate_positive("x", x)
    __validate_positive("y", y)
    __validate_positive("z", z)
    __validate_positive("elem_size", elem_size)

    output_dir = Path(folder)
    output_dir.mkdir(parents=True, exist_ok=True)

    geo_path = output_dir / f"{name}.geo"
    msh_path = output_dir / f"{name}.msh"

    content = _build_geo_content(x=x, y=y, z=z, elem_size=elem_size)
    geo_path.write_text(content)
    # run gmsh to generate the mesh file
    subprocess.run([str(PATH_GMSH), str(geo_path), "-format", "msh2", "-3", "-o", str(msh_path)], check=True)

    return geo_path, msh_path


